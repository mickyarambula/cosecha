export function translate(locale: Locale, key: string | number | null | undefined, vars?: Vars): string {
  if (key == null) return "";
  const raw = String(key);
  if (!raw) return "";
  const dict = locale === "es" ? ES : EN;
  let out = dict[raw] ?? raw;
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
  }
  return out;
}

export function useT() {
  const locale = usePrefs((s) => s.locale);
  return useCallback((key: string, vars?: Vars) => translate(locale, key, vars), [locale]);
}

export function tNow(key: string, vars?: Vars): string {
  return translate(usePrefs.getState().locale, key, vars);
}

export function localizeText(value: unknown, t: (key: string, vars?: Vars) => string): unknown {
  return typeof value === "string" ? t(value) : value;
}
